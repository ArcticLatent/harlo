fn main() -> Result<(), Box<dyn std::error::Error>> {
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(out.join("lucide.ttf"), lucide_icons::LUCIDE_FONT_BYTES)?;

    let mut table = String::from(
        "// Generated by build.rs from the lucide-icons crate.\n\
         import \"lucide.ttf\";\n\n\
         /// Icon glyphs, drawn in the `lucide` font.\n\
         export global Icons {\n\
         \x20   out property <string> font: \"lucide\";\n",
    );
    for (name, icon) in ICONS {
        let point = u32::from(icon.unicode());
        writeln!(
            table,
            "    out property <string> {name}: \"\\u{{{point:x}}}\";"
        )?;
    }
    table.push_str("}\n");
    std::fs::write(out.join("icons.slint"), table)?;

    // Element names and source positions, which the tests' element queries
    // and Slint's MCP server need; release builds leave them out.
    let debug = std::env::var("PROFILE").is_ok_and(|profile| profile != "release");
    let config = slint_build::CompilerConfiguration::new()
        .with_include_paths(vec![out])
        // The dark variant, whatever the desktop's scheme: Harlo is dark.
        .with_style("fluent-dark".to_owned())
        .with_debug_info(debug);
    slint_build::compile_with_config("ui/app.slint", config)?;
    Ok(())
}
